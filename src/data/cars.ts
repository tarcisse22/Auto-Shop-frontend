export function getCarById(id: string): Car | undefined {
  return cars.find((car) => car.id === id);
}

export function getCarsByCategory(category: string): Car[] {
  return cars.filter((car) => car.category === category);
}

export function searchCars(query: string): Car[] {
  const lower = query.toLowerCase();
  return cars.filter(
    (car) =>
      car.name.toLowerCase().includes(lower) ||
      car.brand.toLowerCase().includes(lower) ||
      car.category.toLowerCase().includes(lower) ||
      car.tags.some((tag) => tag.toLowerCase().includes(lower)) ||
      car.specs.engine.toLowerCase().includes(lower)
  );
}

export function getSimilarCars(car: Car, limit = 4): Car[] {
  return cars
    .filter((c) => c.id !== car.id)
    .map((c) => ({
      car: c,
      score:
        (c.category === car.category ? 3 : 0) +
        (c.brand === car.brand ? 2 : 0) +
        c.tags.filter((t) => car.tags.includes(t)).length,
    }))
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map((item) => item.car);
}
